package intrinsic_println_int;

/**
 * The Java source of the kit case intrinsic-println-int: {@code System.out.println} of one String
 * prints it and a newline, as {@code println} does.
 */
public final class Case {
    /** Prints a label and a count. */
    public static void show(long n) {
        System.out.println("count " + n);
    }
}
