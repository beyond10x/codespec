//! The CLI reference page, walked from the clap definition of `codespec` (`codespec_cli::Cli`).

use clap::CommandFactory as _;

use crate::{SOURCE, cell, front_matter};

/// Where the CLI reference lands, relative to the repository root.
pub const PAGE: &str = "website/docs/reference/cli.md";

/// Where the clap definition lives, relative to the repository root.
const DEFINITION: &str = "crates/cli/src/lib.rs";

fn text(value: Option<&clap::builder::StyledStr>) -> String {
    value.map(ToString::to_string).unwrap_or_default()
}

/// One row per argument of `command`: how it is written, whether it is required, its default, the
/// environment variable it falls back to, and its help.
fn arguments(command: &clap::Command) -> Vec<[String; 5]> {
    command
        .get_arguments()
        .filter(|arg| !matches!(arg.get_id().as_str(), "help" | "version"))
        .map(|arg| {
            let value = arg
                .get_value_names()
                .and_then(|names| names.first().map(ToString::to_string))
                .unwrap_or_else(|| arg.get_id().as_str().to_uppercase());
            let written = match arg.get_long() {
                Some(long) if !arg.get_action().takes_values() => format!("--{long}"),
                Some(long) => format!("--{long} <{value}>"),
                None => format!("<{value}>"),
            };
            let defaults: Vec<String> = arg
                .get_default_values()
                .iter()
                .map(|default| default.to_string_lossy().into_owned())
                .filter(|default| default != "false")
                .collect();
            let env = arg
                .get_env()
                .map(|name| format!("`{}`", name.to_string_lossy()))
                .unwrap_or_else(|| "none".to_owned());
            let mut help = cell(&text(arg.get_long_help().or(arg.get_help())));
            if !help.is_empty() && !help.ends_with('.') {
                help.push('.');
            }
            [
                format!("`{written}`"),
                if arg.is_required_set() { "yes" } else { "no" }.to_owned(),
                if defaults.is_empty() {
                    "none".to_owned()
                } else {
                    format!("`{}`", defaults.join(", "))
                },
                env,
                help,
            ]
        })
        .collect()
}

/// The CLI reference page for the command line `root`.
pub fn page_for(mut root: clap::Command) -> String {
    root.build();
    let name = root.get_name().to_owned();
    let mut out = front_matter(
        &format!("{name} CLI reference"),
        &format!("{name} CLI"),
        &format!(
            "Every command and option of the {name} command line, generated from its clap definition."
        ),
        1,
    );
    out.push_str(&format!(
        "# `{name}`\n\nGenerated by `codespec-docs` from the clap definition in \
         [`{DEFINITION}`]({SOURCE}/{DEFINITION}). It lists only commands that exist. \
         `{name} --version` prints the version, and `--help` after any command prints the same \
         text.\n\n> {}\n\n## Commands\n\n| Command | What it does |\n|---|---|\n",
        cell(&text(root.get_about())),
    ));
    let subcommands: Vec<clap::Command> = root
        .get_subcommands()
        .filter(|sub| sub.get_name() != "help")
        .cloned()
        .collect();
    for sub in &subcommands {
        let written = format!("{name} {}", sub.get_name());
        out.push_str(&format!(
            "| [`{written}`](#{}) | {} |\n",
            written.replace(' ', "-"),
            cell(&text(sub.get_about()))
        ));
    }
    for mut sub in subcommands {
        let written = format!("{name} {}", sub.get_name());
        out.push_str(&format!(
            "\n## `{written}`\n\n{}\n\n```text\n{}\n```\n",
            cell(&text(sub.get_long_about().or(sub.get_about()))),
            sub.render_usage().to_string().trim_end()
        ));
        let rows = arguments(&sub);
        if !rows.is_empty() {
            out.push_str(
                "\n| Argument | Required | Default | Environment | Meaning |\n|---|---|---|---|---|\n",
            );
            for row in rows {
                out.push_str(&format!("| {} |\n", row.join(" | ")));
            }
        }
    }
    out.push_str(
        "\n## Exit status\n\n0 on success. 1 when a document is refused (unknown field, unknown \
         kind, an untyped expression, another format, not canonical under `--canonical`), when an \
         adapter is missing, exits non-zero or prints a document the model refuses, and when the \
         harness finds a difference; the reason is printed on stderr as `codespec: <reason>`. \
         Clap's own usage errors exit 2.\n",
    );
    out
}

/// The CLI reference page for `codespec`.
pub fn page() -> String {
    page_for(codespec_cli::Cli::command())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_command_and_its_arguments_are_listed() {
        let page = page();
        assert!(page.contains("# generated by codespec-docs, do not edit"));
        assert!(page.contains("custom_edit_url: null"));
        for command in ["validate", "schema", "read", "pass", "write", "harness"] {
            assert!(
                page.contains(&format!("\n## `codespec {command}`\n")),
                "{command}"
            );
        }
        assert!(page.contains("| `--adapters <ADAPTERS>` | yes | none | `CODESPEC_ADAPTERS` |"));
        assert!(page.contains("| `--seeds <SEEDS>` | no | `200` | none |"));
        assert!(page.contains("| `--build-dir <BUILD_DIR>` | no | `target/harness` | none |"));
        assert!(page.contains("| `--canonical` | no | none | none |"));
        assert!(!page.contains("`codespec help`"));
    }
}
