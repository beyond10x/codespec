//! The showcase: one program through codespec, from the checked-in files of `examples/greeter`.
//! Every code block on the page, the landing's code pair and the `cir/1` diagram are read from
//! those files here, so they cannot drift from what `task examples` writes.

use std::fs;
use std::path::Path;

use codespec_model::Module;
use serde_json::json;

use crate::{Result, TREE, diagram, front_matter};

/// Where the showcase page lands, relative to the repository root.
pub const PAGE: &str = "website/docs/examples/greeter.md";
/// The landing's hero art, a `b10x-code-pair/1` document.
pub const CODE_PAIR: &str = "website/data/greeter-code-pair.json";
/// The diagram of the passed `cir/1` document.
pub const DIAGRAM: &str = "website/static/img/greeter-cir.svg";

const EXAMPLE: &str = "examples/greeter";
const SOURCE: &str = "examples/greeter/source/greeter.go";
const READ: &str = "examples/greeter/greeter.read.cir.json";
const PASSED: &str = "examples/greeter/greeter.cir.json";
const GO: &str = "examples/greeter/out/go/greeter.go";
const RUST: &str = "examples/greeter/out/rust/src/lib.rs";
const REFUSALS: &str = "examples/greeter/out/rust/refusals.json";

pub(crate) fn read(root: &Path, relative: &str) -> Result<String> {
    fs::read_to_string(root.join(relative)).map_err(|e| format!("reading {relative}: {e}"))
}

pub(crate) fn module(root: &Path, relative: &str) -> Result<Module> {
    Module::from_json(read(root, relative)?.as_bytes()).map_err(|e| format!("{relative}: {e}"))
}

pub(crate) fn fence(language: &str, title: &str, code: &str) -> String {
    format!(
        "```{language} title=\"{title}\"\n{}\n```\n",
        code.trim_end_matches('\n')
    )
}

/// The lines of `text` from the first line starting with `start` up to and including the next line
/// that is exactly `end` (or the end of the text).
pub(crate) fn excerpt(text: &str, start: &str, end: Option<&str>) -> Result<String> {
    let lines: Vec<&str> = text.lines().collect();
    let first = lines
        .iter()
        .position(|l| l.starts_with(start))
        .ok_or_else(|| format!("no line starts with {start:?}"))?;
    let last = match end {
        Some(end) => {
            first
                + lines[first..]
                    .iter()
                    .position(|l| *l == end)
                    .ok_or_else(|| format!("no {end:?} after {start:?}"))?
        }
        None => lines.len() - 1,
    };
    Ok(lines[first..=last].join("\n"))
}

pub(crate) fn func_json(m: &Module, name: &str) -> Result<String> {
    let f = m
        .funcs
        .iter()
        .find(|f| f.name == name)
        .ok_or_else(|| format!("{} has no func {name}", m.name))?;
    serde_json::to_string_pretty(f).map_err(|e| e.to_string())
}

/// The showcase page.
fn page(root: &Path) -> Result<String> {
    let source = read(root, SOURCE)?;
    let read_module = module(root, READ)?;
    let passed = module(root, PASSED)?;
    let go = read(root, GO)?;
    let rust = read(root, RUST)?;
    let refusals = read(root, REFUSALS)?;
    let facts = serde_json::to_string_pretty(&passed.facts).map_err(|e| e.to_string())?;
    let mut out = front_matter(
        "Showcase: one program through codespec",
        "Showcase: greeter",
        "A Go greeting service read into cir/1, passed, and written as Go and as Rust, every block taken from the checked-in example.",
        1,
    );
    out.push_str(&format!(
        "# One program through codespec\n\n\
         Generated by `codespec-docs` from the checked-in files of \
         [`{EXAMPLE}`]({TREE}/{EXAMPLE}); `task examples` writes them and `task check` fails when \
         any of them, or this page, drifts. The direction shown is Go → `cir/1` → Rust, and Go → \
         `cir/1` → Go.\n\n\
         :::note[The other direction]\n\nRust → `cir/1` → Go runs on \
         [`examples/inventory`]({TREE}/examples/inventory): a hand-written Rust crate that \
         `codespec-read-rust` reads, written as Go and as Rust and compared under the harness.\
         \n\n:::\n\n\
         ## 1. The source\n\n\
         A small in-memory greeting service in Go. `cir/1` has no network I/O, so this is a \
         service object rather than a server: a call such as `http.ListenAndServe` is read as a \
         `foreign` statement (\"expression outside cir/1\") and the Rust writer refuses the \
         function that holds it.\n\n{}\n\
         ## 2. Read: Go → `cir/1`\n\n\
         ```shell-session\n$ codespec read --lang go {EXAMPLE}/source --out {READ} --adapters target/adapters\n```\n\n\
         The Go reader (`codespec-read-go`, on `go/types`) writes one `cir/1` module: {} types, {} \
         sentinel errors, {} functions, {} refusals. Every expression carries its type. This is \
         `Count` as read:\n\n{}\n\
         ## 3. Pass: `cir/1` → `cir/1`\n\n\
         ```shell-session\n$ codespec pass {READ} --out {PASSED}\n```\n\n\
         `lookup-guard` turns the comma-ok lookup and its early return into one `lookup_else` \
         statement, and the facts pass records what every writer needs to know about the whole \
         module:\n\n{}\n\
         `Count` after the pass:\n\n{}\n\
         ## The `cir/1` document as a tree\n\n\
         Generated by `codespec-docs` from [`{PASSED}`]({TREE}/{PASSED}): the module, its types, \
         errors and functions, each function's statements and each statement's expressions, with \
         kind and type. Nested expressions are collapsed into one line.\n\n\
         ![The cir/1 module greeter as a tree of declarations, statements and expressions](/img/greeter-cir.svg)\n\n\
         ## 4. Write: `cir/1` → Go\n\n\
         ```shell-session\n$ codespec write --lang go {READ} --out {EXAMPLE}/out/go --adapters target/adapters\n```\n\n\
         The Go writer (`codespec-write-go`) builds a `go/ast` tree and prints it with \
         `go/printer`. The result differs from the source only by the generated-code header it starts with.\n\n{}\n\
         ## 5. Write: `cir/1` → Rust\n\n\
         ```shell-session\n$ codespec write --lang rust {PASSED} --out {EXAMPLE}/out/rust --adapters target/adapters\n```\n\n\
         The Rust writer (`codespec-write-rust`, on `syn` and `prettyplease`) reads its mappings \
         off the facts: `Greet` is `fallible`, so it returns `Result<String, Error>`; `Count` is \
         `comma_ok` and `read_only`, so it takes `&self` and returns `Option<i64>`; the sentinel \
         error becomes a variant of one `Error` enum; Go's `int` is `i64` with wrapping \
         arithmetic. It refused nothing:\n\n{}\n{}\n\
         ## What this does not show\n\n\
         - The [harness](/docs/concepts/harness) compares implementations byte for byte on \
         seeded traces. It has trace formats for `orders`, `inventory` and `series` only, so `greeter` is \
         checked by its build and by equality with the checked-in outputs, not by the harness.\n\
         - Writing `g.greeted[name]++` instead of `g.greeted[name] = g.greeted[name] + 1` is \
         refused by the Rust writer today (\"a write into a map entry's value\"); the example \
         uses the form it writes.\n",
        fence("go", "examples/greeter/source/greeter.go", &source),
        read_module.types.len(),
        read_module.errors.len(),
        read_module.funcs.len(),
        read_module.refusals.len(),
        fence("json", "greeter.read.cir.json, funcs: Count", &func_json(&read_module, "Count")?),
        fence("json", "greeter.cir.json, facts", &facts),
        fence("json", "greeter.cir.json, funcs: Count", &func_json(&passed, "Count")?),
        fence("go", "examples/greeter/out/go/greeter.go", &go),
        fence("json", "examples/greeter/out/rust/refusals.json", &refusals),
        fence("rust", "examples/greeter/out/rust/src/lib.rs", &rust),
    ));
    Ok(out)
}

/// The landing's code pair: the Go methods and the Rust `impl` written from them.
fn code_pair(root: &Path) -> Result<String> {
    let source = read(root, SOURCE)?;
    let rust = read(root, RUST)?;
    let document = json!({
        "format": "b10x-code-pair/1",
        "from": {
            "title": "greeter.go",
            "language": "go",
            "code": excerpt(&source, "func (g *Greeter) Greet", None)?,
        },
        "to": {
            "title": "out/rust/src/lib.rs",
            "language": "rust",
            "code": excerpt(&rust, "impl Greeter {", Some("}"))?,
        },
        "via": "codespec read --lang go · codespec pass · codespec write --lang rust",
        "recordedWith": "codespec-docs, from examples/greeter",
    });
    serde_json::to_string_pretty(&document)
        .map(|text| text + "\n")
        .map_err(|e| e.to_string())
}

/// The showcase page, the landing's code pair and the diagram.
pub fn outputs(root: &Path) -> Result<Vec<(&'static str, String)>> {
    let passed = module(root, PASSED)?;
    Ok(vec![
        (PAGE, page(root)?),
        (CODE_PAIR, code_pair(root)?),
        (
            DIAGRAM,
            diagram::svg(&passed, "The cir/1 module greeter after codespec pass"),
        ),
    ])
}

#[cfg(test)]
mod tests {
    use super::*;

    fn root() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
    }

    #[test]
    fn the_showcase_carries_the_source_the_cir_and_both_outputs() {
        let generated = outputs(&root()).unwrap();
        let page = &generated[0].1;
        assert!(page.contains("```go title=\"examples/greeter/source/greeter.go\""));
        assert!(page.contains("```rust title=\"examples/greeter/out/rust/src/lib.rs\""));
        assert!(page.contains("\"k\": \"lookup_else\""));
        assert!(page.contains("pub fn greet(&mut self, name: String) -> Result<String, Error>"));
        let pair = &generated[1].1;
        assert!(pair.contains("\"format\": \"b10x-code-pair/1\""));
        let svg = &generated[2].1;
        assert!(svg.starts_with("<svg "));
        assert!(svg.contains("lookup_else n = g.greeted[name], else:"));
        assert_eq!(svg, &outputs(&root()).unwrap()[2].1);
    }

    #[test]
    fn an_excerpt_runs_to_its_end_line() {
        let text = "a\nimpl X {\n    b\n}\nc\n";
        assert_eq!(
            excerpt(text, "impl X", Some("}")).unwrap(),
            "impl X {\n    b\n}"
        );
        assert_eq!(excerpt(text, "c", None).unwrap(), "c");
        assert!(excerpt(text, "zzz", None).is_err());
    }
}
