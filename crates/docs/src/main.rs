/// The first line of every generated page's front matter.
const FRONT_MATTER_HEADER: &str = "# generated by codespec-docs, do not edit";
/// The line every generated Markdown page carries directly after its front matter.
const HEADER: &str = "<!-- generated by codespec-docs, do not edit -->";
/// A file in the repository on GitHub, by path.
const SOURCE: &str = "https://github.com/beyond10x/codespec/blob/main";
/// A directory in the repository on GitHub, by path.
const TREE: &str = "https://github.com/beyond10x/codespec/tree/main";
/// Every documentation page, generated or written by hand, relative to the repository root.
const DOCS: &str = "website/docs";

type Result<T> = std::result::Result<T, String>;

#[derive(Parser)]
#[command(
    name = "codespec-docs",
    about = "Generate and check the derived pages of the codespec documentation site"
)]
struct Cli {
    #[command(subcommand)]
    command: Action,
}

#[derive(Subcommand)]
enum Action {
    /// Regenerate the reference pages and the status data, or check them for drift.
    Generate {
        /// Write nothing; fail when a generated file is missing, stale or hand-edited.
        #[arg(long)]
        check: bool,
        /// Repository root.
        #[arg(long, default_value = ".")]
        root: PathBuf,
        /// The built adapters and runners the conformance reports are run with, relative to the
        /// root.
        #[arg(long, default_value = "target/adapters")]
        adapters: PathBuf,
    },
    /// Bind a built site to its source commit: write `.well-known/b10x-site.json` and the route
    /// inventory `.well-known/b10x-routes.json` into it.
    Provenance {
        /// The built site, `website/build`.
        #[arg(long)]
        site: PathBuf,
        /// The full Git revision the site was built from.
        #[arg(long)]
        commit: String,
    },
}

/// Whether `line` is an admonition whose title is not in brackets (`:::caution Planned`), which
/// Docusaurus prints as raw text.
fn is_raw_admonition(line: &str) -> bool {
    let Some(rest) = line.strip_prefix(":::") else {
        return false;
    };
    let kind = rest.bytes().take_while(u8::is_ascii_lowercase).count();
    let rest = &rest[kind..];
    let spaces = rest.bytes().take_while(|b| *b == b' ').count();
    kind > 0
        && spaces > 0
        && rest[spaces..]
            .chars()
            .next()
            .is_some_and(|c| !c.is_whitespace())
}

/// `file:line` of every raw admonition title in the Markdown and MDX pages under `dir`.
fn raw_admonitions(dir: &Path) -> Result<Vec<String>> {
    let mut entries: Vec<PathBuf> = fs::read_dir(dir)
        .map_err(|e| format!("reading {}: {e}", dir.display()))?
        .map(|entry| entry.map(|e| e.path()).map_err(|e| e.to_string()))
        .collect::<Result<_>>()?;
    entries.sort();
    let mut found = Vec::new();
    for path in entries {
        if path.is_dir() {
            found.extend(raw_admonitions(&path)?);
        } else if path
            .extension()
            .is_some_and(|ext| ext == "md" || ext == "mdx")
        {
            let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
            for (n, line) in text.lines().enumerate() {
                if is_raw_admonition(line) {
                    found.push(format!("{}:{}", path.display(), n + 1));
                }
            }
        }
    }
    Ok(found)
}

/// The project-site publication record for one build of the `/codespec/` site.
fn site_manifest(commit: &str) -> Result<String> {
    if commit.len() != 40
        || !commit.bytes().all(|b| b.is_ascii_hexdigit())
        || commit == "0".repeat(40)
    {
        return Err("commit must be a nonzero full Git revision".to_owned());
    }
    Ok(format!(
        "{{\n  \"baseUrl\": \"/codespec/\",\n  \"commit\": \"{commit}\",\n  \"repository\": \"codespec\",\n  \"schema\": \"b10x-project-site/v1\"\n}}"
    ))
}

fn write_provenance(site: &Path, commit: &str) -> Result<()> {
    let manifest = site_manifest(commit)?;
    if !site.join("index.html").is_file() {
        return Err(format!("{} holds no built site", site.display()));
    }
    let io = |e: std::io::Error| format!("writing site provenance: {e}");
    fs::create_dir_all(site.join(".well-known")).map_err(io)?;
    fs::write(site.join(".well-known/b10x-site.json"), manifest).map_err(io)?;
    let routes = routes::inventory(site, commit)?;
    fs::write(site.join(".well-known/b10x-routes.json"), routes).map_err(io)?;
    fs::write(site.join(".nojekyll"), "").map_err(io)?;
    Ok(())
}

fn yaml_string(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

/// `value` as one Markdown table cell: on one line, with `|` escaped.
fn cell(value: &str) -> String {
    value
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('|', "\\|")
}

/// The front matter of a generated page: the generator line, title, label, sidebar position,
/// description and no edit link, then the generated-page comment.
fn front_matter(title: &str, label: &str, description: &str, position: u32) -> String {
    format!(
        "---\n{FRONT_MATTER_HEADER}\ntitle: {}\nsidebar_label: {}\nsidebar_position: {position}\ndescription: {}\ncustom_edit_url: null\n---\n\n{HEADER}\n\n",
        yaml_string(title),
        yaml_string(label),
        yaml_string(description),
    )
}

/// Every generated file, keyed by path relative to the repository root.
fn outputs(root: &Path) -> Result<Vec<(&'static str, String)>> {
    let mut all = vec![
        (cli::PAGE, cli::page()),
        (crates::PAGE, crates::page(root)?),
        (cir::PAGE, cir::page(root)?),
        (status::DATA, status::document(root)?),
    ];
    all.extend(showcase::outputs(root)?);
    all.extend(series::outputs(root)?);
    Ok(all)
}

/// The conformance reports of the in-repository adapters, by path: role and language. Every
/// adapter this repository ships has one.
const REPORTS: &[(&str, &str, &str)] = &[
    ("website/data/conformance/reader-go.json", "reader", "go"),
    (
        "website/data/conformance/reader-rust.json",
        "reader",
        "rust",
    ),
    (
        "website/data/conformance/reader-java.json",
        "reader",
        "java",
    ),
    (
        "website/data/conformance/reader-groovy.json",
        "reader",
        "groovy",
    ),
    ("website/data/conformance/writer-go.json", "writer", "go"),
    (
        "website/data/conformance/writer-rust.json",
        "writer",
        "rust",
    ),
];

/// One generated directory: its path relative to the root and every file under it, by path
/// relative to the directory.
type Tree = (String, Vec<(String, Vec<u8>)>);

/// The reader corpora `conformance/reader/<lang>`, built from the kit's case sources by
/// [`reader_corpus`].
fn corpora(root: &Path) -> Result<Vec<Tree>> {
    CORPUS_LANGS
        .iter()
        .map(|lang| {
            Ok((
                format!("conformance/reader/{lang}"),
                reader_corpus(&root.join("conformance"), lang)?,
            ))
        })
        .collect()
}

/// Every file of `dir`, by `/`-separated path relative to it, sorted.
fn files_in(dir: &Path, rel: &str, out: &mut Vec<String>) -> Result<()> {
    let here = dir.join(rel);
    let mut entries: Vec<_> = fs::read_dir(&here)
        .map_err(|e| format!("{}: {e}", here.display()))?
        .map(|e| e.map(|e| e.file_name().to_string_lossy().into_owned()))
        .collect::<std::result::Result<_, _>>()
        .map_err(|e| format!("{}: {e}", here.display()))?;
    entries.sort();
    for name in entries {
        let path = if rel.is_empty() {
            name
        } else {
            format!("{rel}/{name}")
        };
        if dir.join(&path).is_dir() {
            files_in(dir, &path, out)?;
        } else {
            out.push(path);
        }
    }
    Ok(())
}

/// How the files under `dir` differ from `files`: each one that differs, is missing, or is extra.
fn tree_drift(dir: &Path, files: &[(String, Vec<u8>)]) -> Result<Vec<String>> {
    let mut found = Vec::new();
    if dir.is_dir() {
        files_in(dir, "", &mut found)?;
    }
    let mut out = Vec::new();
    for (rel, content) in files {
        match fs::read(dir.join(rel)) {
            Ok(have) if &have == content => {}
            Ok(_) => out.push(format!("{rel} differs")),
            Err(_) => out.push(format!("{rel} is missing")),
        }
    }
    for rel in found {
        if !files.iter().any(|(f, _)| *f == rel) {
            out.push(format!("{rel} is not built from any case source"));
        }
    }
    out.sort();
    Ok(out)
}

/// Replace `dir` with exactly `files`.
fn write_tree(dir: &Path, files: &[(String, Vec<u8>)]) -> Result<()> {
    if dir.exists() {
        fs::remove_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    }
    for (rel, content) in files {
        let path = dir.join(rel);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
        }
        fs::write(&path, content).map_err(|e| format!("{}: {e}", path.display()))?;
    }
    Ok(())
}

/// Write one generated directory, or with `check` fail naming every file that drifted.
fn settle_tree(root: &Path, (relative, files): &Tree, check: bool) -> Result<()> {
    let dir = root.join(relative);
    if check {
        let drift = tree_drift(&dir, files)?;
        if !drift.is_empty() {
            return Err(format!(
                "{relative} is not what the kit's case sources build ({}); run `task docs-generate`",
                drift.join(", ")
            ));
        }
        println!("{relative}: current, {} files", files.len());
    } else {
        write_tree(&dir, files)?;
        println!("{relative}: written, {} files", files.len());
    }
    Ok(())
}

/// Each report of [`REPORTS`], run now with the kit `conformance/`, the readers' corpus
/// `conformance/reader/<lang>` and the programs in `adapters`, working under
/// `target/codespec-docs-conform/`.
fn reports(root: &Path, adapters: &Path) -> Result<Vec<(&'static str, Report)>> {
    let mut out = Vec::new();
    for (path, role, lang) in REPORTS {
        let report = conform_adapter(&Target {
            adapters: root.join(adapters),
            role: (*role).to_string(),
            lang: (*lang).to_string(),
            kit: root.join("conformance"),
            corpus: None,
            work: root.join(format!("target/codespec-docs-conform/{role}-{lang}")),
        })
        .map_err(|e| format!("{path}: {e}"))?;
        println!("{path}: {}", summary_line(&report));
        out.push((*path, report));
    }
    Ok(out)
}

/// The support matrix from the feature list, the manifest each adapter of [`REPORTS`] in
/// `adapters` prints for `--describe`, and `reports`, the reports just run.
fn support_matrix(
    root: &Path,
    adapters: &Path,
    reports: &[(&'static str, Report)],
) -> Result<String> {
    let mut list = Vec::new();
    for ((path, role, lang), (_, report)) in REPORTS.iter().zip(reports) {
        let program = Process(
            std::path::absolute(root.join(adapters).join(format!(
                "codespec-{}-{lang}",
                if *role == "reader" { "read" } else { "write" }
            )))
            .map_err(|e| e.to_string())?,
        );
        let manifest = program.describe().map_err(|e| format!("{path}: {e}"))?;
        list.push(support::Adapter {
            role,
            lang,
            manifest,
            report: Some(report.clone()),
        });
    }
    let features = fs::read(root.join("schemas/cir-1.features.json"))
        .map_err(|e| format!("schemas/cir-1.features.json: {e}"))?;
    let doc = support::document(&features, &root.join("conformance"), &list)?;
    for (column, counts) in support::totals(&doc)? {
        let shown: Vec<String> = counts
            .iter()
            .filter(|(_, n)| *n > 0)
            .map(|(s, n)| format!("{n} {s}"))
            .collect();
        println!("{}: {column}: {}", support::DATA, shown.join(", "));
    }
    Ok(doc)
}

/// Write one generated file, or with `check` compare it with what is there; a stale report names
/// what differs in it.
fn settle(root: &Path, relative: &str, content: &str, check: bool) -> Result<()> {
    let path = root.join(relative);
    if check {
        match fs::read_to_string(&path) {
            Ok(found) if found == content => println!("{relative}: current"),
            Ok(found) => {
                let mut why = String::new();
                if let (Ok(old), Ok(new)) = (
                    read_report(found.as_bytes()),
                    read_report(content.as_bytes()),
                ) {
                    why = format!(": {}", differences(&old, &new).join("; "));
                }
                return Err(format!(
                    "{relative} is stale or edited{why}; run `task docs-generate`"
                ));
            }
            Err(_) => return Err(format!("{relative} is missing; run `task docs-generate`")),
        }
    } else {
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
        }
        fs::write(&path, content).map_err(|e| format!("{relative}: {e}"))?;
        println!("{relative}: written");
    }
    Ok(())
}

fn generate(root: &Path, adapters: &Path, check: bool) -> Result<()> {
    // The reader corpora first, which the reports run on; then the reports, which the support
    // matrix and the status data read.
    for tree in corpora(root)? {
        settle_tree(root, &tree, check)?;
    }
    let ran = reports(root, adapters)?;
    for (relative, report) in &ran {
        settle(root, relative, &report_json(report), check)?;
    }
    settle(
        root,
        support::DATA,
        &support_matrix(root, adapters, &ran)?,
        check,
    )?;
    let writer_go = ran
        .iter()
        .find(|(path, _)| *path == guide::REPORT)
        .map(|(_, r)| r)
        .ok_or_else(|| format!("no report {}", guide::REPORT))?;
    settle(root, guide::PAGE, &guide::page(root, writer_go)?, check)?;
    let all = outputs(root)?;
    for (relative, content) in &all {
        settle(root, relative, content, check)?;
    }
    if check {
        let raw = raw_admonitions(&root.join(DOCS))?;
        if !raw.is_empty() {
            return Err(format!(
                "raw admonition titles (write `:::kind[Title]`): {}",
                raw.join(", ")
            ));
        }
        println!("{DOCS}: no raw admonition titles");
    }
    Ok(())
}

fn main() -> ExitCode {
    let result = match Cli::parse().command {
        Action::Generate {
            check,
            root,
            adapters,
        } => generate(&root, &adapters, check),
        Action::Provenance { site, commit } => write_provenance(&site, &commit)
            .map(|()| println!("{}: bound to {commit}", site.display())),
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("codespec-docs: {e}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn root() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
    }

    fn scratch(name: &str) -> PathBuf {
        let dir = root().join(format!(
            "target/codespec-docs-test/{name}-{}",
            std::process::id()
        ));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn provenance_names_the_commit_and_refuses_a_bad_one() {
        let commit = "b73ffce0000000000000000000000000000000aa";
        let manifest = site_manifest(commit).unwrap();
        assert!(manifest.contains(&format!("\"commit\": \"{commit}\"")));
        assert!(manifest.contains("\"schema\": \"b10x-project-site/v1\""));
        assert!(manifest.contains("\"baseUrl\": \"/codespec/\""));
        assert!(site_manifest("b73ffce").is_err());
        assert!(site_manifest(&"0".repeat(40)).is_err());
        assert!(site_manifest(&format!("{}\"", &commit[..39])).is_err());

        let site = scratch("provenance");
        assert!(write_provenance(&site, commit).is_err());
        fs::write(site.join("index.html"), "").unwrap();
        write_provenance(&site, commit).unwrap();
        let written = fs::read_to_string(site.join(".well-known/b10x-site.json")).unwrap();
        assert_eq!(written, manifest);
        let routes = fs::read_to_string(site.join(".well-known/b10x-routes.json")).unwrap();
        assert!(routes.contains("\"path\": \"/codespec/\""));
        assert!(site.join(".nojekyll").is_file());
        fs::remove_dir_all(site).unwrap();
    }

    #[test]
    fn raw_admonition_titles_are_found_and_bracketed_ones_pass() {
        for raw in [":::caution Planned", ":::note  These", ":::info Decided"] {
            assert!(is_raw_admonition(raw), "{raw}");
        }
        for fine in [
            ":::caution[Planned]",
            ":::",
            ":::note",
            ":::note ",
            "::: note T",
        ] {
            assert!(!is_raw_admonition(fine), "{fine}");
        }
        let dir = scratch("admonitions");
        fs::create_dir_all(dir.join("concepts")).unwrap();
        fs::write(dir.join("index.md"), ":::caution[Planned]\nok\n:::\n").unwrap();
        fs::write(dir.join("concepts/a.md"), "text\n:::caution Planned\n:::\n").unwrap();
        let found = raw_admonitions(&dir).unwrap();
        assert_eq!(found.len(), 1);
        assert!(found[0].ends_with("concepts/a.md:2"), "{found:?}");
        fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn every_reader_corpus_is_built_from_the_kit_case_sources() {
        let root = root();
        for (dir, files) in corpora(&root).unwrap() {
            assert_eq!(
                tree_drift(&root.join(&dir), &files).unwrap(),
                Vec::<String>::new(),
                "{dir} differs from the kit's case sources; run `task docs-generate`"
            );
        }
    }

    #[test]
    fn a_corpus_entry_that_differs_from_its_case_source_is_named() {
        let dir = scratch("corpus-drift");
        let files = vec![
            ("a/Case.java".to_string(), b"class A {}\n".to_vec()),
            ("a/calls.json".to_string(), b"{}\n".to_vec()),
            ("b/case.go".to_string(), b"package b\n".to_vec()),
        ];
        write_tree(&dir, &files).unwrap();
        assert!(tree_drift(&dir, &files).unwrap().is_empty());
        fs::write(dir.join("a/Case.java"), "class A { }\n").unwrap();
        fs::write(dir.join("c.txt"), "extra").unwrap();
        fs::remove_file(dir.join("b/case.go")).unwrap();
        assert_eq!(
            tree_drift(&dir, &files).unwrap(),
            vec![
                "a/Case.java differs".to_string(),
                "b/case.go is missing".to_string(),
                "c.txt is not built from any case source".to_string(),
            ]
        );
        write_tree(&dir, &files).unwrap();
        assert!(tree_drift(&dir, &files).unwrap().is_empty());
        fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn every_generated_file_is_current_in_this_tree() {
        let root = root();
        for (relative, content) in outputs(&root).unwrap() {
            let found = fs::read_to_string(root.join(relative))
                .unwrap_or_else(|_| panic!("{relative} is missing; run `task docs-generate`"));
            assert!(
                found == content,
                "{relative} is stale; run `task docs-generate`"
            );
        }
    }
}
