// The writer: a cir/1 module to one go/ast file. Every node is built without source positions;
// go/printer lays it out and go/format normalises the result. Parentheses are inserted only where
// Go's precedence would otherwise regroup an operand, because cir/1 carries the tree, not the
// source's parentheses.

type writer struct {
	m       *Module
	types   map[string]*TypeDecl
	imports map[string]bool
	used    map[string]bool
	untyped map[string]Type
	pos     string
	err     error
	// breaks holds the enclosing loops and switches, innermost last; a cir/1 `break` inside a
	// switch leaves the loop around it, which Go spells with a label on that loop.
	breaks []*breakable
}

type breakable struct {
	loop  bool
	label string
}

type piece struct {
	doc  string
	node ast.Decl
}

var tokens = func() map[string]token.Token {
	out := map[string]token.Token{}
	for t := token.ILLEGAL; t <= token.TILDE; t++ {
		if t.IsOperator() {
			out[t.String()] = t
		}
	}
	return out
}()

// stdPackages are the standard-library packages a foreign Go statement may name; the writer
// imports each one such a statement uses where no local of that name is in scope.
var stdPackages = map[string]string{
	"bytes": "bytes", "context": "context", "errors": "errors", "fmt": "fmt", "io": "io",
	"math": "math", "os": "os", "sort": "sort", "strconv": "strconv", "strings": "strings",
	"sync": "sync", "time": "time",
}

func write(m *Module) ([]byte, error) {
	w := &writer{m: m, types: map[string]*TypeDecl{}, imports: map[string]bool{}, untyped: map[string]Type{}}
	for i := range m.Types {
		w.types[m.Types[i].Name] = &m.Types[i]
	}
	for i := range m.Consts {
		if d, ok := untypedConst(&m.Consts[i]); ok {
			w.untyped[m.Consts[i].Name] = d
		}
	}
	pieces, err := w.decls()
	if err != nil {
		return nil, err
	}
	out, err := w.render(pieces)
	if err != nil {
		return nil, err
	}
	if missing := missingImports(out); len(missing) > 0 {
		for _, p := range missing {
			w.imports[p] = true
		}
		return w.render(pieces)
	}
	return out, nil
}

// missingImports type-checks the written file against empty stand-ins for its imports and
// returns every standard package a foreign statement names where no local of that name is in
// scope. go/types resolves the scope, so a local declared elsewhere in the function does not hide
// the package.
func missingImports(src []byte) []string {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "", src, 0)
	if err != nil {
		return nil
	}
	found := map[string]bool{}
	conf := types.Config{
		Importer: standIns{},
		Error: func(err error) {
			if te, ok := err.(types.Error); ok {
				name, isUndefined := strings.CutPrefix(te.Msg, "undefined: ")
				if path := stdPackages[name]; isUndefined && path != "" {
					found[path] = true
				}
			}
		},
	}
	_, _ = conf.Check(f.Name.Name, fset, []*ast.File{f}, nil)
	var out []string
	for p := range found {
		out = append(out, p)
	}
	sort.Strings(out)
	return out
}

type standIns struct{}

func (standIns) Import(path string) (*types.Package, error) {
	p := types.NewPackage(path, path[strings.LastIndex(path, "/")+1:])
	p.MarkComplete()
	return p, nil
}

func (w *writer) render(pieces []piece) ([]byte, error) {
	m := w.m
	var b bytes.Buffer
	b.WriteString("// Code generated by codespec-write-go from cir/1. DO NOT EDIT.\n\n")
	if m.Doc != "" {
		b.WriteString(comment(m.Doc))
	}
	fmt.Fprintf(&b, "package %s\n\n", m.Name)
	if len(w.imports) > 0 {
		var paths []string
		for p := range w.imports {
			paths = append(paths, p)
		}
		sort.Strings(paths)
		imp := &ast.GenDecl{Tok: token.IMPORT}
		for _, p := range paths {
			imp.Specs = append(imp.Specs, &ast.ImportSpec{Path: &ast.BasicLit{Kind: token.STRING, Value: strconv.Quote(p)}})
		}
		pieces = append([]piece{{node: imp}}, pieces...)
	}
	fset := token.NewFileSet()
	for _, p := range pieces {
		if p.doc != "" {
			b.WriteString(comment(p.doc))
		}
		if err := printer.Fprint(&b, fset, p.node); err != nil {
			return nil, err
		}
		b.WriteString("\n\n")
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("the written Go does not parse: %v", err)
	}
	return out, nil
}

func comment(doc string) string {
	var b strings.Builder
	for _, line := range strings.Split(doc, "\n") {
		if line == "" {
			b.WriteString("//\n")
		} else {
			b.WriteString("// " + line + "\n")
		}
	}
	return b.String()
}

func (w *writer) refuse(format string, a ...any) {
	if w.err == nil {
		w.err = fmt.Errorf("%s: %s", w.pos, fmt.Sprintf(format, a...))
	}
}

// decls builds every declaration in layout order, then any the layout does not name in model order.
func (w *writer) decls() ([]piece, error) {
	m := w.m
	done := map[string]bool{}
	byKey := map[string]func() []piece{}
	var order []string
	for i := range m.Types {
		td := &m.Types[i]
		k := "type:" + td.Name
		byKey[k], order = func() []piece { return w.typeDecl(td) }, append(order, k)
	}
	for i := range m.Consts {
		c := &m.Consts[i]
		k := "const:" + c.Name
		byKey[k], order = func() []piece { return []piece{{node: w.constDecl(c)}} }, append(order, k)
	}
	for i := range m.Errors {
		e := &m.Errors[i]
		k := "error:" + e.Name
		byKey[k], order = func() []piece { return []piece{{node: w.errorDecl(e)}} }, append(order, k)
	}
	for i := range m.Funcs {
		f := &m.Funcs[i]
		k := "func:" + f.key()
		byKey[k], order = func() []piece { return []piece{{doc: f.Doc, node: w.funcDecl(f)}} }, append(order, k)
	}
	var out []piece
	for _, k := range append(append([]string{}, m.Layout...), order...) {
		if done[k] {
			continue
		}
		build, ok := byKey[k]
		if !ok {
			return nil, fmt.Errorf("layout names %q, which the module does not declare", k)
		}
		done[k] = true
		out = append(out, build()...)
		if w.err != nil {
			return nil, w.err
		}
	}
	return out, nil
}

func ident(name string) *ast.Ident { return ast.NewIdent(name) }

func (w *writer) typ(t Type) ast.Expr {
	switch t.K {
	case "int":
		name := "int"
		if !t.Signed {
			name = "uint"
		}
		if t.Width != "platform" {
			name += t.Width
		}
		return ident(name)
	case "bool", "string", "error", "any":
		return ident(t.K)
	case "unit":
		return &ast.StructType{Fields: &ast.FieldList{}}
	case "named":
		return ident(t.Name)
	case "ptr":
		return &ast.StarExpr{X: w.typ(*t.Elem)}
	case "slice":
		return &ast.ArrayType{Elt: w.typ(*t.Elem)}
	case "map":
		return &ast.MapType{Key: w.typ(*t.Key), Value: w.typ(*t.Elem)}
	case "chan":
		dir := map[string]ast.ChanDir{"send": ast.SEND, "recv": ast.RECV, "both": ast.SEND | ast.RECV}[t.Dir]
		return &ast.ChanType{Dir: dir, Value: w.typ(*t.Elem)}
	case "tuple":
		w.refuse("a tuple type outside a function's results has no Go form")
		return ident("any")
	}
	w.refuse("type %q has no Go form", t.K)
	return ident("any")
}

func (w *writer) typeDecl(td *TypeDecl) []piece {
	w.pos = td.Pos
	spec := &ast.TypeSpec{Name: ident(td.Name)}
	decl := &ast.GenDecl{Tok: token.TYPE, Specs: []ast.Spec{spec}}
	switch td.K {
	case "struct":
		fl := &ast.FieldList{}
		for _, f := range td.Fields {
			fl.List = append(fl.List, &ast.Field{Names: []*ast.Ident{ident(f.Name)}, Type: w.typ(f.T)})
		}
		spec.Type = &ast.StructType{Fields: fl}
	case "newtype":
		spec.Type = w.typ(*td.Under)
	case "enum":
		spec.Type = w.typ(*td.Under)
		var vs []Variant
		if err := json.Unmarshal(td.Variants, &vs); err != nil {
			w.refuse("enum %s: %v", td.Name, err)
			return nil
		}
		consts := &ast.GenDecl{Tok: token.CONST}
		for _, v := range vs {
			consts.Specs = append(consts.Specs, &ast.ValueSpec{
				Names: []*ast.Ident{ident(v.Name)}, Type: ident(td.Name), Values: []ast.Expr{w.expr(v.Value)},
			})
		}
		return []piece{{doc: td.Doc, node: decl}, {node: consts}}
	case "union":
		w.refuse("union %s: Go has no tagged union", td.Name)
		return nil
	default:
		w.refuse("type declaration %q has no Go form", td.K)
		return nil
	}
	return []piece{{doc: td.Doc, node: decl}}
}

func (w *writer) constDecl(c *Const) ast.Decl {
	w.pos = c.Pos
	spec := &ast.ValueSpec{Names: []*ast.Ident{ident(c.Name)}, Values: []ast.Expr{w.expr(c.Value)}}
	if _, ok := w.untyped[c.Name]; !ok {
		spec.Type = w.typ(c.T)
	}
	return &ast.GenDecl{Tok: token.CONST, Specs: []ast.Spec{spec}}
}

// untypedConst reports whether a constant is written untyped: its type is a basic one and is the
// type Go gives its literal by default, so the untyped constant reads back as the same document
// while staying usable wherever the source's untyped constant was.
func untypedConst(c *Const) (Type, bool) {
	if c.T.K == "named" {
		return Type{}, false
	}
	d, ok := litDefault(c.Value.Value)
	if !ok || c.Value.K != "lit" || !sameType(d, c.T) {
		return Type{}, false
	}
	return d, true
}

var (
	goInt    = Type{K: "int", Width: "platform", Signed: true}
	goRune   = Type{K: "int", Width: "32", Signed: true}
	goBool   = Type{K: "bool"}
	goString = Type{K: "string"}
	goFloat  = Type{K: "float"}
)

func sameType(a, b Type) bool { return reflect.DeepEqual(a, b) }

// litDefault is the type Go gives an untyped constant written as value. Floating-point and complex
// constants get a type cir/1 does not have, so they never equal a cir/1 type.
func litDefault(value string) (Type, bool) {
	x, err := parser.ParseExpr(value)
	if err != nil {
		return Type{}, false
	}
	for {
		u, ok := x.(*ast.UnaryExpr)
		if !ok {
			break
		}
		x = u.X
	}
	switch x := x.(type) {
	case *ast.BasicLit:
		switch x.Kind {
		case token.INT:
			return goInt, true
		case token.CHAR:
			return goRune, true
		case token.STRING:
			return goString, true
		default:
			return goFloat, true
		}
	case *ast.Ident:
		if x.Name == "true" || x.Name == "false" {
			return goBool, true
		}
	}
	return Type{}, false
}

// defaultType is the type Go gives the written form of e when := binds it: ok is false when e is
// written as a typed expression, whose type is then t itself. nilType reports an untyped nil.
func (w *writer) defaultType(e Expr) (d Type, ok, nilType bool) {
	switch e.K {
	case "lit":
		d, ok = litDefault(e.Value)
		return d, ok, false
	case "nil":
		return Type{}, false, true
	case "const":
		d, ok = w.untyped[e.Name]
		return d, ok, false
	case "zero":
		switch e.T.K {
		case "int":
			return goInt, true, false
		case "bool":
			return goBool, true, false
		case "string":
			return goString, true, false
		case "error", "any", "ptr", "slice", "map", "chan":
			return Type{}, false, true
		}
	case "unop":
		if e.Op == "-" || e.Op == "+" || e.Op == "^" || e.Op == "!" {
			return w.defaultType(*e.X)
		}
	case "binop":
		x, xok, _ := w.defaultType(*e.X)
		y, yok, _ := w.defaultType(*e.Y)
		if !xok || !yok {
			return Type{}, false, false
		}
		switch e.Op {
		case "==", "!=", "<", "<=", ">", ">=", "&&", "||":
			return goBool, true, false
		case "<<", ">>":
			return x, true, false
		}
		for _, d := range []Type{goFloat, goRune, goInt} {
			if sameType(x, d) || sameType(y, d) {
				return d, true, false
			}
		}
		return x, true, false
	}
	return Type{}, false, false
}

// bind is the right-hand side := gives the type t: converted when Go's default type for the
// written form is another type. An untyped nil cannot be bound by := at all; ok false says so.
func (w *writer) bind(e Expr, x ast.Expr) (ast.Expr, bool) {
	d, untyped, isNil := w.defaultType(e)
	if isNil {
		return x, false
	}
	if !untyped || sameType(d, *e.T) {
		return x, true
	}
	var fun ast.Expr = w.typ(*e.T)
	switch fun.(type) {
	case *ast.StarExpr, *ast.ChanType, *ast.FuncType:
		fun = &ast.ParenExpr{X: fun}
	}
	return &ast.CallExpr{Fun: fun, Args: []ast.Expr{x}}, true
}

func (w *writer) errorDecl(e *ErrorVar) ast.Decl {
	w.imports["errors"] = true
	call := &ast.CallExpr{
		Fun:  &ast.SelectorExpr{X: ident("errors"), Sel: ident("New")},
		Args: []ast.Expr{&ast.BasicLit{Kind: token.STRING, Value: strconv.Quote(e.Message)}},
	}
	return &ast.GenDecl{Tok: token.VAR, Specs: []ast.Spec{&ast.ValueSpec{
		Names: []*ast.Ident{ident(e.Name)}, Values: []ast.Expr{call},
	}}}
}

func (w *writer) funcDecl(f *Func) ast.Decl {
	w.pos = f.Pos
	w.used = map[string]bool{}
	params := &ast.FieldList{}
	for _, p := range f.Params {
		w.used[p.Name] = true
		params.List = append(params.List, &ast.Field{Names: []*ast.Ident{ident(p.Name)}, Type: w.typ(p.T)})
	}
	var results *ast.FieldList
	if len(f.Results) > 0 {
		results = &ast.FieldList{}
		for _, t := range f.Results {
			results.List = append(results.List, &ast.Field{Type: w.typ(t)})
		}
	}
	d := &ast.FuncDecl{Name: ident(f.Name), Type: &ast.FuncType{Params: params, Results: results}}
	if f.Recv != nil {
		w.used[f.Recv.Name] = true
		d.Recv = &ast.FieldList{List: []*ast.Field{{Names: []*ast.Ident{ident(f.Recv.Name)}, Type: w.typ(f.Recv.T)}}}
	}
	for _, n := range w.moduleNames() {
		w.used[n] = true
	}
	collectNames(f.Body, w.used)
	d.Body = &ast.BlockStmt{List: w.stmts(f.Body)}
	return d
}

// moduleNames is every name the module declares at package level, enum variants included.
func (w *writer) moduleNames() []string {
	m := w.m
	var out []string
	for _, td := range m.Types {
		out = append(out, td.Name)
		if td.K == "enum" {
			var vs []Variant
			if json.Unmarshal(td.Variants, &vs) == nil {
				for _, v := range vs {
					out = append(out, v.Name)
				}
			}
		}
	}
	for _, c := range m.Consts {
		out = append(out, c.Name)
	}
	for _, e := range m.Errors {
		out = append(out, e.Name)
	}
	for _, f := range m.Funcs {
		if f.Recv == nil {
			out = append(out, f.Name)
		}
	}
	return out
}

// collectNames records every name a body binds or reads, so a name the writer invents is fresh.
func collectNames(body []Stmt, used map[string]bool) {
	var ex func(e *Expr)
	ex = func(e *Expr) {
		if e == nil {
			return
		}
		if e.K == "var" {
			used[e.Name] = true
		}
		ex(e.X)
		ex(e.Y)
		ex(e.Index)
		for i := range e.Args {
			ex(&e.Args[i])
		}
		for i := range e.Fields {
			ex(&e.Fields[i].Value)
		}
	}
	for i := range body {
		s := &body[i]
		for _, n := range s.Names {
			used[n] = true
		}
		used[s.Name], used[s.Key], used[s.Val] = true, true, true
		if s.K == "foreign" {
			for _, n := range foreignNames(s.Src) {
				used[n] = true
			}
		}
		for _, e := range []*Expr{s.X, s.Cond, s.Over, s.Tag, s.Chan, s.Map, s.Index} {
			ex(e)
		}
		for _, l := range [][]Expr{s.Lhs, s.Rhs, s.Results} {
			for j := range l {
				ex(&l[j])
			}
		}
		collectNames(s.Then, used)
		collectNames(s.Else, used)
		collectNames(s.Body, used)
		for _, c := range s.Cases {
			collectNames(c.Body, used)
		}
	}
}

func (w *writer) fresh(base string) string {
	name := base
	for i := 1; w.used[name]; i++ {
		name = fmt.Sprintf("%s%d", base, i)
	}
	w.used[name] = true
	return name
}

func (w *writer) stmts(list []Stmt) []ast.Stmt {
	var out []ast.Stmt
	for i := range list {
		out = append(out, w.stmt(&list[i])...)
	}
	return out
}

func (w *writer) exprs(xs []Expr) []ast.Expr {
	var out []ast.Expr
	for _, x := range xs {
		out = append(out, w.expr(x))
	}
	return out
}

func idents(names ...string) []ast.Expr {
	var out []ast.Expr
	for _, n := range names {
		out = append(out, ident(n))
	}
	return out
}

// loop writes body into block and returns the loop, labeled when a break inside a switch in it
// needs a label to leave it.
func (w *writer) loop(l ast.Stmt, block *ast.BlockStmt, body []Stmt) ast.Stmt {
	b := &breakable{loop: true}
	w.breaks = append(w.breaks, b)
	block.List = w.stmts(body)
	w.breaks = w.breaks[:len(w.breaks)-1]
	if b.label != "" {
		return &ast.LabeledStmt{Label: ident(b.label), Stmt: l}
	}
	return l
}

// single writes a for loop's init or post statement, which is one Go statement.
func (w *writer) single(s *Stmt) ast.Stmt {
	out := w.stmt(s)
	if len(out) != 1 {
		w.refuse("for clause %q has no single Go statement", s.K)
		return &ast.EmptyStmt{}
	}
	return out[0]
}

func (w *writer) stmt(s *Stmt) []ast.Stmt {
	w.pos = s.Pos
	switch s.K {
	case "let":
		tok := token.ASSIGN
		for _, n := range s.Names {
			if n != "_" {
				tok = token.DEFINE
			}
		}
		rhs := w.exprs(s.Rhs)
		if len(s.Rhs) == len(s.Names) {
			for i, e := range s.Rhs {
				x, ok := w.bind(e, rhs[i])
				if !ok && len(s.Names) == 1 {
					return []ast.Stmt{&ast.DeclStmt{Decl: &ast.GenDecl{Tok: token.VAR, Specs: []ast.Spec{
						&ast.ValueSpec{Names: []*ast.Ident{ident(s.Names[0])}, Type: w.typ(*e.T)},
					}}}}
				}
				if !ok {
					x = &ast.CallExpr{Fun: &ast.ParenExpr{X: w.typ(*e.T)}, Args: []ast.Expr{x}}
				}
				rhs[i] = x
			}
		}
		return []ast.Stmt{&ast.AssignStmt{Lhs: idents(s.Names...), Tok: tok, Rhs: rhs}}
	case "var":
		return []ast.Stmt{&ast.DeclStmt{Decl: &ast.GenDecl{Tok: token.VAR, Specs: []ast.Spec{
			&ast.ValueSpec{Names: []*ast.Ident{ident(s.Name)}, Type: w.typ(*s.T)},
		}}}}
	case "assign":
		tok := token.ASSIGN
		if s.Op != "" {
			t, ok := tokens[s.Op]
			if !ok || t < token.ADD_ASSIGN || t > token.AND_NOT_ASSIGN {
				w.refuse("assignment operator %q has no Go form", s.Op)
			}
			tok = t
		}
		return []ast.Stmt{&ast.AssignStmt{Lhs: w.exprs(s.Lhs), Tok: tok, Rhs: w.exprs(s.Rhs)}}
	case "incr":
		return []ast.Stmt{&ast.IncDecStmt{X: w.expr(*s.X), Tok: token.INC}}
	case "decr":
		return []ast.Stmt{&ast.IncDecStmt{X: w.expr(*s.X), Tok: token.DEC}}
	case "if":
		return []ast.Stmt{w.ifStmt(s)}
	case "for_range":
		r := &ast.RangeStmt{X: header(w.expr(*s.Over))}
		switch {
		case s.Val != "_":
			r.Key, r.Value, r.Tok = ident(s.Key), ident(s.Val), token.DEFINE
		case s.Key != "_":
			r.Key, r.Tok = ident(s.Key), token.DEFINE
		}
		r.Body = &ast.BlockStmt{}
		return []ast.Stmt{w.loop(r, r.Body, s.Body)}
	case "for":
		f := &ast.ForStmt{Body: &ast.BlockStmt{}}
		if s.Init != nil {
			f.Init = w.single(s.Init)
		}
		if s.Cond != nil {
			f.Cond = header(w.expr(*s.Cond))
		}
		if s.Post != nil {
			f.Post = w.single(s.Post)
		}
		w.pos = s.Pos
		return []ast.Stmt{w.loop(f, f.Body, s.Body)}
	case "break":
		var label *ast.Ident
		if n := len(w.breaks); n > 0 && !w.breaks[n-1].loop {
			for i := n - 1; i >= 0; i-- {
				if b := w.breaks[i]; b.loop {
					if b.label == "" {
						b.label = w.fresh("loop")
					}
					label = ident(b.label)
					break
				}
			}
		}
		return []ast.Stmt{&ast.BranchStmt{Tok: token.BREAK, Label: label}}
	case "continue":
		return []ast.Stmt{&ast.BranchStmt{Tok: token.CONTINUE}}
	case "switch":
		sw := &ast.SwitchStmt{Body: &ast.BlockStmt{}}
		if s.Tag != nil {
			sw.Tag = header(w.expr(*s.Tag))
		}
		for _, c := range s.Cases {
			var vals []ast.Expr
			for _, v := range w.exprs(c.Values) {
				vals = append(vals, header(v))
			}
			w.breaks = append(w.breaks, &breakable{})
			body := w.stmts(c.Body)
			w.breaks = w.breaks[:len(w.breaks)-1]
			sw.Body.List = append(sw.Body.List, &ast.CaseClause{List: vals, Body: body})
		}
		return []ast.Stmt{sw}
	case "return":
		return []ast.Stmt{&ast.ReturnStmt{Results: w.exprs(s.Results)}}
	case "expr":
		return []ast.Stmt{&ast.ExprStmt{X: w.expr(*s.X)}}
	case "send":
		return []ast.Stmt{&ast.SendStmt{Chan: w.expr(*s.Chan), Value: w.expr(*s.X)}}
	case "lookup_else":
		pos := s.Pos
		ok := w.fresh("ok")
		get := &ast.AssignStmt{
			Lhs: idents(s.Name, ok), Tok: token.DEFINE,
			Rhs: []ast.Expr{&ast.IndexExpr{X: primary(w.expr(*s.Map)), Index: w.expr(*s.Index)}},
		}
		then := w.stmts(s.Then)
		w.pos = pos
		return []ast.Stmt{get, &ast.IfStmt{Cond: &ast.UnaryExpr{Op: token.NOT, X: ident(ok)}, Body: &ast.BlockStmt{List: then}}}
	case "foreign":
		return w.foreign(s)
	}
	w.refuse("statement %q has no Go form", s.K)
	return nil
}

func (w *writer) ifStmt(s *Stmt) *ast.IfStmt {
	w.pos = s.Pos
	st := &ast.IfStmt{Cond: header(w.expr(*s.Cond)), Body: &ast.BlockStmt{List: w.stmts(s.Then)}}
	switch {
	case len(s.Else) == 1 && s.Else[0].K == "if":
		st.Else = w.ifStmt(&s.Else[0])
	case len(s.Else) > 0:
		st.Else = &ast.BlockStmt{List: w.stmts(s.Else)}
	}
	return st
}

// foreign splices a Go statement the reader kept verbatim; source in any other language is refused.
func (w *writer) foreign(s *Stmt) []ast.Stmt {
	if s.Lang != "go" {
		w.refuse("foreign statement in %q cannot be written as Go (%s)", s.Lang, s.Reason)
		return nil
	}
	f, err := parser.ParseFile(token.NewFileSet(), "", "package p\n\nfunc _() {\n"+s.Src+"\n}\n", 0)
	if err != nil {
		w.refuse("foreign Go statement does not parse: %v", err)
		return nil
	}
	list := f.Decls[0].(*ast.FuncDecl).Body.List
	for _, st := range list {
		stripPositions(st)
	}
	return list
}

// foreignNames is every identifier a foreign Go statement holds, so a name the writer invents
// cannot capture or be captured by one of them.
func foreignNames(src string) []string {
	f, err := parser.ParseFile(token.NewFileSet(), "", "package p\n\nfunc _() {\n"+src+"\n}\n", 0)
	if err != nil {
		return nil
	}
	var out []string
	ast.Inspect(f.Decls[0].(*ast.FuncDecl).Body, func(n ast.Node) bool {
		if id, ok := n.(*ast.Ident); ok {
			out = append(out, id.Name)
		}
		return true
	})
	return out
}

var posType = reflect.TypeOf(token.NoPos)

// marker positions carry meaning by being valid: CallExpr.Ellipsis is a spread call's `...`,
// TypeSpec.Assign an alias's `=`. They keep a valid placeholder; every other position is zeroed.
var marker = map[string]bool{"Ellipsis": true, "Assign": true}

// stripPositions zeroes every position in a parsed subtree, so go/printer lays it out like the
// nodes the writer builds rather than by offsets into a file it never sees.
func stripPositions(root ast.Node) {
	ast.Inspect(root, func(n ast.Node) bool {
		if n == nil {
			return false
		}
		v := reflect.ValueOf(n)
		if v.Kind() != reflect.Pointer || v.Elem().Kind() != reflect.Struct {
			return true
		}
		v = v.Elem()
		for i := 0; i < v.NumField(); i++ {
			f := v.Field(i)
			if f.Type() != posType || !f.CanSet() {
				continue
			}
			if marker[v.Type().Field(i).Name] && f.Int() != 0 {
				f.SetInt(1)
			} else {
				f.SetInt(0)
			}
		}
		return true
	})
}

const primaryPrec = token.HighestPrec

func prec(e ast.Expr) int {
	switch e := e.(type) {
	case *ast.BinaryExpr:
		return e.Op.Precedence()
	case *ast.UnaryExpr, *ast.StarExpr:
		return token.UnaryPrec
	}
	return primaryPrec
}

func parenBelow(e ast.Expr, p int) ast.Expr {
	if prec(e) < p {
		return &ast.ParenExpr{X: e}
	}
	return e
}

// primary is the operand of a selector, index or call: anything but a primary expression is
// parenthesised.
func primary(e ast.Expr) ast.Expr { return parenBelow(e, primaryPrec) }

// header parenthesises a composite literal of a named type at the top of an if, for or switch
// header, where Go would read its brace as the start of the block.
func header(e ast.Expr) ast.Expr {
	switch x := e.(type) {
	case *ast.CompositeLit:
		switch x.Type.(type) {
		case *ast.Ident, *ast.SelectorExpr:
			return &ast.ParenExpr{X: x}
		}
	case *ast.BinaryExpr:
		x.X, x.Y = header(x.X), header(x.Y)
	case *ast.UnaryExpr:
		x.X = header(x.X)
	case *ast.StarExpr:
		x.X = header(x.X)
	case *ast.SelectorExpr:
		x.X = header(x.X)
	case *ast.IndexExpr:
		x.X = header(x.X)
	case *ast.CallExpr:
		x.Fun = header(x.Fun)
	}
	return e
}

var intrinsics = map[string][2]string{
	"sprintf": {"fmt", "Sprintf"}, "errorf": {"fmt", "Errorf"}, "println": {"fmt", "Println"},
	"append": {"", "append"}, "len": {"", "len"},
}

func (w *writer) expr(e Expr) ast.Expr {
	switch e.K {
	case "lit":
		x, err := parser.ParseExpr(e.Value)
		if err != nil {
			w.refuse("literal %q is not Go: %v", e.Value, err)
			return ident("nil")
		}
		stripPositions(x)
		return x
	case "nil":
		return ident("nil")
	case "var", "const", "errvar":
		return ident(e.Name)
	case "field":
		return &ast.SelectorExpr{X: primary(w.expr(*e.X)), Sel: ident(e.Name)}
	case "index":
		return &ast.IndexExpr{X: primary(w.expr(*e.X)), Index: w.expr(*e.Index)}
	case "call":
		return &ast.CallExpr{Fun: ident(e.Name), Args: w.exprs(e.Args)}
	case "method":
		return &ast.CallExpr{Fun: &ast.SelectorExpr{X: primary(w.expr(*e.X)), Sel: ident(e.Name)}, Args: w.exprs(e.Args)}
	case "binop":
		op, ok := tokens[e.Op]
		if !ok || op.Precedence() == token.LowestPrec {
			w.refuse("binary operator %q has no Go form", e.Op)
			return ident("nil")
		}
		p := op.Precedence()
		return &ast.BinaryExpr{X: parenBelow(w.expr(*e.X), p), Op: op, Y: parenBelow(w.expr(*e.Y), p+1)}
	case "unop":
		x := parenBelow(w.expr(*e.X), token.UnaryPrec)
		if e.Op == "*" {
			return &ast.StarExpr{X: x}
		}
		op, ok := tokens[e.Op]
		if !ok || (op != token.NOT && op != token.SUB && op != token.ADD && op != token.AND && op != token.XOR && op != token.ARROW) {
			w.refuse("unary operator %q has no Go form", e.Op)
			return ident("nil")
		}
		return &ast.UnaryExpr{Op: op, X: x}
	case "struct":
		lit := &ast.CompositeLit{Type: ident(e.Name)}
		for _, f := range e.Fields {
			lit.Elts = append(lit.Elts, &ast.KeyValueExpr{Key: ident(f.Name), Value: w.expr(f.Value)})
		}
		return lit
	case "conv":
		return &ast.CallExpr{Fun: ident(e.Name), Args: []ast.Expr{w.expr(*e.X)}}
	case "make":
		if e.T.K != "map" && e.T.K != "slice" {
			w.refuse("make of a %s has no Go form", e.T.K)
			return ident("nil")
		}
		return &ast.CompositeLit{Type: w.typ(*e.T)}
	case "zero":
		return w.zero(*e.T)
	case "intrinsic":
		in, ok := intrinsics[e.Name]
		if !ok {
			w.refuse("intrinsic %q has no Go form", e.Name)
			return ident("nil")
		}
		var fun ast.Expr = ident(in[1])
		if in[0] != "" {
			w.imports[in[0]] = true
			fun = &ast.SelectorExpr{X: ident(in[0]), Sel: ident(in[1])}
		}
		return &ast.CallExpr{Fun: fun, Args: w.exprs(e.Args)}
	case "to_error":
		return w.expr(*e.X)
	}
	w.refuse("expression %q has no Go form", e.K)
	return ident("nil")
}

func (w *writer) zero(t Type) ast.Expr {
	switch t.K {
	case "int":
		return &ast.BasicLit{Kind: token.INT, Value: "0"}
	case "bool":
		return ident("false")
	case "string":
		return &ast.BasicLit{Kind: token.STRING, Value: `""`}
	case "error", "any", "ptr", "slice", "map", "chan":
		return ident("nil")
	case "unit":
		return &ast.CompositeLit{Type: w.typ(t)}
	case "named":
		td := w.types[t.Name]
		switch {
		case td == nil:
		case td.K == "struct":
			return &ast.CompositeLit{Type: ident(t.Name)}
		case td.K == "newtype" || td.K == "enum":
			return &ast.CallExpr{Fun: ident(t.Name), Args: []ast.Expr{w.zero(*td.Under)}}
		}
		return &ast.StarExpr{X: &ast.CallExpr{Fun: ident("new"), Args: []ast.Expr{ident(t.Name)}}}
	}
	w.refuse("the zero value of a %s has no Go form", t.K)
	return ident("nil")
}
