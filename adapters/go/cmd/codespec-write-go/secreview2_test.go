// Security review, pass 2, of codespec-write-go: doc comments never become a directive, a build
// constraint or a cgo preamble; the package clause and file name never make a file the go command
// skips; names of every class strict reading admits are refused or written as Go that type-checks.
// Nothing written here is built or run: files are parsed, type-checked or matched by go/build.

import (
	"bytes"
	"encoding/json"
	"go/ast"
	"go/build"
	"go/build/constraint"
	"go/importer"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"testing"
)

// directive reports whether a written comment line is one the go command, the compiler, cgo or
// go/build reads as more than text.
func directive(line string) bool {
	l := strings.TrimLeft(line, " \t")
	if constraint.IsGoBuild(l) || constraint.IsPlusBuild(l) {
		return true
	}
	for _, p := range []string{"//go:", "//line ", "//line\t", "/*line ", "//export ", "//extern ", "//sys ", "#cgo"} {
		if strings.HasPrefix(l, p) {
			return true
		}
	}
	return false
}

// Every doc shape that is a directive with its "// " prefix taken away, or that go/format's doc
// comment reformatting could turn into one, stays text: no written line is a directive, the
// file matches go/build on this platform, and the package is the one written.
func TestSecreview2NoDocLineBecomesADirective(t *testing.T) {
	lines := []string{
		"go:build ignore", "+build ignore", " +build ignore", "\t+build ignore", "+build\tignore",
		"\u00a0+build ignore", "\u0085+build ignore", "+build ignore\r", "\r+build ignore",
		"go:generate touch secreview2", "go:embed *", "go:linkname x runtime.x", "go:noinline",
		"line secreview2.go:1", "export Secreview2", "extern secreview2", "#cgo LDFLAGS: -lsecreview2",
		"/*line x.go:1*/", "*/ func init() { panic(1) } /*", "x\r//go:build ignore",
		"x\u2028//go:build ignore", "Code generated by hand. DO NOT EDIT.",
	}
	for i, l := range lines {
		for _, where := range [][]string{{"doc"}, {"funcs", "0", "doc"}} {
			t.Run(strconv.Itoa(i)+"-"+where[0], func(t *testing.T) {
				doc := docAt(t, "conformance/cases/op-add/case.cir.json")
				if where[0] == "doc" {
					doc["doc"] = "Para.\n\n" + l + "\n\n\t" + l + "\n" + l
				} else {
					set(t, doc, where, "Add adds.\n"+l+"\n\n  "+l)
				}
				b, err := json.Marshal(doc)
				if err != nil {
					t.Fatal(err)
				}
				out := scratch(t)
				if err := run(bytes.NewReader(b), out); err != nil {
					return // refused
				}
				src, err := os.ReadFile(filepath.Join(out, "op_add.go"))
				if err != nil {
					t.Fatal(err)
				}
				for _, line := range strings.Split(string(src), "\n") {
					if directive(line) {
						t.Errorf("doc line %q became the directive %q:\n%s", l, line, src)
					}
				}
				ok, err := build.Default.MatchFile(out, "op_add.go")
				if err != nil || !ok {
					t.Errorf("the written file does not build here (%v, %v):\n%s", ok, err, src)
				}
				f, err := parser.ParseFile(token.NewFileSet(), "", src, parser.ParseComments)
				if err != nil {
					t.Fatalf("written Go does not parse: %v", err)
				}
				for _, d := range f.Decls {
					if fd, ok := d.(*ast.FuncDecl); ok && fd.Name.Name == "init" {
						t.Errorf("doc %q became func init:\n%s", l, src)
					}
				}
			})
		}
	}
}

// An extern of path "C" turns on cgo; the comment right above `import "C"` is the cgo preamble,
// C source and #cgo flags. No doc of the document may become that comment.
func TestSecreview2NoDocBecomesACgoPreamble(t *testing.T) {
	raw, err := os.ReadFile(filepath.Join(repo, "conformance/cases/expr-extern/case.cir.json"))
	if err != nil {
		t.Fatal(err)
	}
	var doc map[string]any
	if err := json.Unmarshal(bytes.ReplaceAll(raw, []byte(`"strconv"`), []byte(`"C"`)), &doc); err != nil {
		t.Fatal(err)
	}
	pre := "#cgo LDFLAGS: -lsecreview2\n#include <stdlib.h>\nstatic int secreview2(void) { return system(\"true\"); }"
	doc["doc"] = pre
	set(t, doc, []string{"funcs", "0", "doc"}, pre)
	b, err := json.Marshal(doc)
	if err != nil {
		t.Fatal(err)
	}
	out := scratch(t)
	if err := run(bytes.NewReader(b), out); err != nil {
		return // refused
	}
	src, err := os.ReadFile(filepath.Join(out, "expr_extern.go"))
	if err != nil {
		t.Fatal(err)
	}
	f, err := parser.ParseFile(token.NewFileSet(), "", src, parser.ParseComments)
	if err != nil {
		t.Fatalf("written Go does not parse: %v", err)
	}
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok || g.Tok != token.IMPORT {
			continue
		}
		for _, s := range g.Specs {
			is := s.(*ast.ImportSpec)
			if is.Path.Value != `"C"` {
				continue
			}
			if g.Doc != nil || is.Doc != nil {
				t.Errorf("the doc became the cgo preamble:\n%s", src)
			}
		}
	}
}

// The package clause is the module name. go/build and the go command ignore every file whose
// package clause is `documentation`, whatever its file name: the written package is then empty.
func TestSecreview2APackageClauseIsNeverOneTheGoCommandIgnores(t *testing.T) {
	for _, name := range []string{"documentation", "Documentation", "op_add"} {
		t.Run(name, func(t *testing.T) {
			out, ok := writeNamed(t, name)
			if !ok {
				return // refused
			}
			p, err := build.ImportDir(out, 0)
			if err != nil {
				t.Errorf("module %q: the go command finds no package in what was written: %v (ignored: %v)", name, err, p.IgnoredGoFiles)
				return
			}
			if len(p.GoFiles) != 1 || p.Name != name {
				t.Errorf("module %q: package %q with files %v, ignored %v", name, p.Name, p.GoFiles, p.IgnoredGoFiles)
			}
		})
	}
}

// writeNamed writes op-add renamed to name; false when the writer refuses it.
func writeNamed(t *testing.T, name string) (string, bool) {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(repo, "conformance/cases/op-add/case.cir.json"))
	if err != nil {
		t.Fatal(err)
	}
	var doc map[string]any
	if err := json.Unmarshal(bytes.ReplaceAll(raw, []byte(`"op_add"`), []byte(strconv.Quote(name))), &doc); err != nil {
		t.Fatal(err)
	}
	b, err := json.Marshal(doc)
	if err != nil {
		t.Fatal(err)
	}
	out := scratch(t)
	return out, run(bytes.NewReader(b), out) == nil
}

// A module name with this machine's own _GOOS or _GOARCH suffix builds here and nowhere else;
// plainGoFile refuses it only because it matches against a platform that does not exist. The
// secreview1 names (_windows, _arm64) do not match linux/amd64 either way, so they do not hold
// this.
func TestSecreview2AModuleNameWithThisPlatformsSuffixIsRefused(t *testing.T) {
	for _, name := range []string{"op_add_" + build.Default.GOOS, "op_add_" + build.Default.GOARCH, "op_add_" + build.Default.GOOS + "_" + build.Default.GOARCH} {
		t.Run(name, func(t *testing.T) {
			if _, ok := writeNamed(t, name); ok {
				t.Errorf("module %q was written as %s.go, which builds on %s/%s only", name, name, build.Default.GOOS, build.Default.GOARCH)
			}
		})
	}
}

// The written file is <module>.go; on Windows a base name CON, NUL, AUX, PRN, COM1 or LPT1
// opens the device, not a file in the output directory, whatever the extension (before
// Windows 11). Checked by name only: this machine has no such device.
func TestSecreview2AModuleFileIsNeverAWindowsDeviceName(t *testing.T) {
	for _, name := range []string{"con", "nul", "aux", "prn", "com1", "lpt1", "CON"} {
		t.Run(name, func(t *testing.T) {
			if _, ok := writeNamed(t, name); ok {
				t.Errorf("module %q was written as %s.go, a device name on Windows", name, name)
			}
		})
	}
}

// secreview2Names is one name from each class strict reading's is_name admits.
var secreview2Names = []string{
	"a\u0301", "\u0301a", "a\u0903", "a\u0660", "\u0660a", "\u2160", "a\u00b2", "a\u203fb",
	"\u203fa", "a\u20ac", "\u20aca", "a$", "\u4e00", "a\u02b0", "a\u00b7", "a\u0387", "\u24b6",
	"a\ufe0f", "\u3164", "\u212a", "\ufb01", "a\u2e2f", "1a", "r#type",
}

// Every admitted name, given to the first parameter of op-add, is refused or written as Go that
// go/types checks without error.
func TestSecreview2EveryAdmittedNameIsRefusedOrTypeChecks(t *testing.T) {
	for i, name := range secreview2Names {
		t.Run(strconv.Itoa(i), func(t *testing.T) {
			doc := docAt(t, "conformance/cases/op-add/case.cir.json")
			set(t, doc, []string{"funcs", "0", "params", "0", "name"}, name)
			set(t, doc, []string{"funcs", "0", "body", "0", "results", "0", "x", "name"}, name)
			b, err := json.Marshal(doc)
			if err != nil {
				t.Fatal(err)
			}
			out := scratch(t)
			if err := run(bytes.NewReader(b), out); err != nil {
				return // refused
			}
			src, err := os.ReadFile(filepath.Join(out, "op_add.go"))
			if err != nil {
				t.Fatal(err)
			}
			fset := token.NewFileSet()
			f, err := parser.ParseFile(fset, "", src, 0)
			if err != nil {
				t.Fatalf("%q written, does not parse: %v\n%s", name, err, src)
			}
			conf := types.Config{Importer: importer.Default()}
			if _, err := conf.Check("op_add", fset, []*ast.File{f}, nil); err != nil {
				t.Errorf("%q written, does not type-check: %v\n%s", name, err, src)
			}
		})
	}
}
